# поиск пароля в прошивке
# цифры 0-9, всего 4 цифры
# значит пароль должен лежать в памяти как четвёрка байт
# от 0 до 9. проходим по области кода (первые 0x7000 байт)
# и выцепляем все такие четвёрки

with open("dump.bin", "rb") as f:
    code = f.read(0x7000)

# ищем 4-байтные последовательности, где все значения в диапазоне 0..9
for i in range(len(code) - 4):
    sub = code[i:i + 4]
    if all(0 <= b <= 9 for b in sub):
        # отсеиваем длинные серии нулей
        if not all(b == 0 for b in sub):
            print(f"Offset 0x{i:04X}: {[int(b) for b in sub]}")
